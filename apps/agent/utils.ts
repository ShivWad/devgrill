/**
 * Extracts a JSON object from an LLM response.
 *
 * Handles common formatting artifacts produced by models:
 * - Removes <think>...</think> reasoning blocks
 * - Removes markdown code fences (```json ... ```)
 * - Extracts the outermost JSON object if additional prose exists
 *
 * This makes parsing more resilient to minor formatting mistakes
 * without requiring a retry.
 *
 * @param raw Raw model response
 * @returns Clean JSON string ready for JSON.parse()
 */
export const extractJson = (raw: string): string => {
  let text = raw.trim();

  // Strip <think>...</think> blocks some reasoning-distilled models emit
  text = text.replace(/<think>[\s\S]*?<\/think>/gi, "").trim();

  // Strip ```json ... ``` or ``` ... ``` fences
  const fenceMatch = text.match(/```(?:json)?\s*([\s\S]*?)```/i);
  if (fenceMatch) {
    text = fenceMatch[1].trim();
  }

  // If there's still leading/trailing prose, grab the outermost {...}
  const firstBrace = text.indexOf("{");
  const lastBrace = text.lastIndexOf("}");
  if (firstBrace !== -1 && lastBrace !== -1 && lastBrace > firstBrace) {
    text = text.slice(firstBrace, lastBrace + 1);
  }

  return text;
};




/**
 * Removes any <think>...</think> blocks from model output.
 *
 * Useful when chaining multiple LLM calls and you want subsequent
 * prompts to consume only the visible analysis rather than internal
 * reasoning traces.
 *
 * @param raw Raw model response
 * @returns Response with all think blocks removed
 */
export const stripThinkTags = (raw: string): string => {
  return raw.replace(/<think>[\s\S]*?<\/think>/gi, "").trim();
};

/**
 * Converts free-form text into a normalized slug suitable for use
 * as a checklist key.
 *
 * Example:
 * "What are the expected traffic patterns?"
 * ->
 * "what_are_the_expected_traffic_patterns"
 *
 * @param text Source text
 * @returns Lowercase underscore-separated slug
 */
export const slugify = (text: string): string =>
  text
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, "")
    .trim()
    .split(/\s+/)
    .join("_");

/**
 * Builds the interview coverage checklist from a generated question.
 *
 * Checklist items are namespaced by interview phase:
 * - req:*    Requirements gathering topics
 * - design:* High-level design topics
 * - deep:*   Deep-dive discussion topics
 * - scale:*  Generic scalability evaluation topics
 *
 * All entries are initialized to false and updated as the
 * interview progresses.
 *
 * @param question Generated interview question configuration
 * @returns Coverage checklist keyed by phase-prefixed identifiers
 */
export const buildChecklist = (
  question: QuestionConfig,
): Record<string, boolean> => {
  const checklist: Record<string, boolean> = {};

  for (const item of question.expectedClarifications) {
    checklist[`req:${slugify(item)}`] = false;
  }

  for (const item of question.keyComponents) {
    checklist[`design:${slugify(item)}`] = false;
  }

  for (const item of question.deepDiveTargets) {
    checklist[`deep:${slugify(item)}`] = false;
  }

  // Generic scale-phase items — same across all questions
  checklist["scale:identified_bottleneck"] = false;
  checklist["scale:proposed_mitigation"] = false;
  checklist["scale:discussed_tradeoff"] = false;
  checklist["scale:back_of_envelope"] = false;

  return checklist;
};

