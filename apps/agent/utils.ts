export interface NodeMetric {
  node: string;
  durationMs: number;
  inputTokens: number;
  cachedTokens: number;       // DeepSeek prompt cache hits (reduces billed input cost)
  outputTokens: number;
  reasoningTokens: number;    // DeepSeek V4-Pro / R1 chain-of-thought tokens (billed as output)
  totalTokens: number;
}

